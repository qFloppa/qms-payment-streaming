import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import solc from "solc";
import { keccak256 } from "viem";

const root = fileURLToPath(new URL("../", import.meta.url));
const compilerVersion = "0.8.38";
if (!solc.version().startsWith(`${compilerVersion}+`)) {
  throw new Error(`Expected solc ${compilerVersion}; run npm ci.`);
}
const sources = {};
for (const name of [
  "contracts/RillStream.sol",
  "contracts/test/Receivers.sol",
]) {
  sources[name] = { content: await readFile(resolve(root, name), "utf8") };
}
const settings = {
  optimizer: { enabled: true, runs: 200 },
  evmVersion: "paris",
  metadata: { bytecodeHash: "none", appendCBOR: false },
  outputSelection: {
    "*": {
      "*": [
        "abi",
        "evm.bytecode.object",
        "evm.deployedBytecode.object",
        "metadata",
      ],
    },
  },
};
const output = JSON.parse(
  solc.compile(JSON.stringify({ language: "Solidity", sources, settings })),
);
for (const diagnostic of output.errors ?? []) {
  if (diagnostic.severity === "error")
    console.error(diagnostic.formattedMessage);
}
if (output.errors?.some(({ severity }) => severity === "error"))
  process.exit(1);
await mkdir(resolve(root, "contracts/artifacts"), { recursive: true });
await mkdir(resolve(root, "src/contracts"), { recursive: true });
for (const [sourceName, contracts] of Object.entries(output.contracts)) {
  for (const [contractName, compiled] of Object.entries(contracts)) {
    if (!compiled.evm.bytecode.object) continue;
    const artifact = {
      contractName,
      sourceName,
      compiler: solc.version(),
      evmVersion: settings.evmVersion,
      settings,
      abi: compiled.abi,
      bytecode: `0x${compiled.evm.bytecode.object}`,
      deployedBytecode: `0x${compiled.evm.deployedBytecode.object}`,
      runtimeHash: keccak256(`0x${compiled.evm.deployedBytecode.object}`),
      metadata: JSON.parse(compiled.metadata),
    };
    await writeFile(
      resolve(root, `contracts/artifacts/${contractName}.json`),
      `${JSON.stringify(artifact, null, 2)}\n`,
    );
    if (contractName === "RillStream") {
      await writeFile(
        resolve(root, "src/contracts/rill.ts"),
        `// Generated by npm run contracts:compile. Do not edit.\nexport const rillAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\nexport const rillRuntimeHash = '${artifact.runtimeHash}' as const;\n`,
      );
      await writeFile(
        resolve(root, "src/contracts/deployment.ts"),
        `// Generated by npm run contracts:compile. Import dynamically on the setup route.\nexport const rillBytecode = '${artifact.bytecode}' as const;\n`,
      );
      console.log(
        `Compiled ${contractName} with solc ${compilerVersion} (${settings.evmVersion}); runtime ${artifact.runtimeHash}`,
      );
    }
  }
}
